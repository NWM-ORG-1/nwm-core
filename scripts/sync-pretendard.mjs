/**
 * Re-generates the self-hosted Pretendard files after upgrading the `pretendard`
 * package: copies the woff2 slices to public/fonts/pretendard/<version>/ and
 * rewrites src/app/pretendard.css. Bump PRELOAD in src/app/layout.tsx if the
 * version changes.
 */
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync("node_modules/pretendard/package.json", "utf8"));
const v = pkg.version;
const src = "node_modules/pretendard/dist/web/variable";
const out = `public/fonts/pretendard/${v}`;
mkdirSync(out, { recursive: true });
for (const f of readdirSync(`${src}/woff2-dynamic-subset`)) copyFileSync(`${src}/woff2-dynamic-subset/${f}`, `${out}/${f}`);
const license = readFileSync(`${src}/pretendardvariable-dynamic-subset.css`, "utf8").match(/^\/\*([\s\S]*?)\*\//);
if (license) writeFileSync(`${out}/LICENSE.txt`, `${license[1].trim()}\n`);
let css = readFileSync(`${src}/pretendardvariable-dynamic-subset.css`, "utf8").replaceAll("./woff2-dynamic-subset/", `/fonts/pretendard/${v}/`);
css = css.replace(/^\/\*[\s\S]*?\*\/\s*/, "");
writeFileSync(
  "src/app/pretendard.css",
  `/*\n * Pretendard Variable — dynamic subset (${v}), self-hosted from /public with immutable caching.\n * Generated by scripts/sync-pretendard.mjs — do not edit by hand.\n */\n${css}`,
);
console.log(`✓ Pretendard ${v} synced`);
